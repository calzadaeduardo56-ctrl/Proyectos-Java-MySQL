    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        boolean hayCamposVacios = false;

        if (jTextField1.getText().trim().isEmpty()) {
            hayCamposVacios = true;
        }
        if (jPasswordField1.getPassword().length == 0) {
            hayCamposVacios = true;
        }

        if (hayCamposVacios) {
            JOptionPane.showMessageDialog(null,
                    "Para poder acceder al sistema debe insertar usuario y contraseña.",
                    "Advertencia",
                    JOptionPane.WARNING_MESSAGE);
            if (jTextField1.getText().trim().isEmpty()) {
                jTextField1.requestFocus();
            } else {
                jPasswordField1.requestFocus();
            }
            return;
        }

// Datos ingresados
        String usuarioIngresado = jTextField1.getText().trim();
        String contraseñaIngresada = new String(jPasswordField1.getPassword()).trim();

        Connection conn = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try (Connection cn = new conexion().conectar()) {

            // 🔹 Primero verificamos si el usuario existe
            String sqlUsuario = "SELECT Contraseña, Nombre, Modulo, Status, Perfil "
                    + "FROM perfilado WHERE Usuario = ?";
            pst = cn.prepareStatement(sqlUsuario);
            pst.setString(1, usuarioIngresado);
            rs = pst.executeQuery();

            if (!rs.next()) {
                // ❌ Usuario no existe
                JOptionPane.showMessageDialog(this,
                        "El usuario no existe.",
                        "Error de autenticación",
                        JOptionPane.ERROR_MESSAGE);
                jTextField1.selectAll();
                jTextField1.requestFocus();
                return;
            }

            // ✅ Usuario encontrado, verificamos contraseña
            String contraseñaReal = rs.getString("Contraseña");
            if (!contraseñaReal.equals(contraseñaIngresada)) {
                // ❌ Contraseña incorrecta
                JOptionPane.showMessageDialog(this,
                        "Contraseña incorrecta.",
                        "Error de autenticación",
                        JOptionPane.ERROR_MESSAGE);
                jPasswordField1.selectAll();
                jPasswordField1.requestFocus();
                return;
            }

            // ✅ Usuario y contraseña correctos
            String nombreEmpleado = rs.getString("Nombre");
            String modulo = rs.getString("Modulo");
            String status = rs.getString("Status");
            String puesto = rs.getString("Perfil");

            if (!"Esta Disponible".equalsIgnoreCase(status.trim())) {
                JOptionPane.showMessageDialog(this,
                        nombreEmpleado + ", el módulo \"" + modulo + "\" no está disponible.\n"
                        + "Podrá acceder hasta que \"" + modulo + "\" esté disponible.",
                        "Módulo no disponible",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 🔹 Abrir ventana según el módulo
            switch (modulo) {

                case "Menu de Modulos":
                    MenuModulos menu = new MenuModulos();
                    menu.setVisible(true);
                    break;

                case "Menu del Supervisor":
                    MenuSupervisor menu1 = new MenuSupervisor();
                    menu1.setVisible(true);
                    break;

                case "Menu del Cajero":
                    MenuCajero menu2 = new MenuCajero();
                    menu2.setVisible(true);
                    break;

                default:
                    JOptionPane.showMessageDialog(this,
                            "El módulo asignado no existe o no está implementado.",
                            "Información",
                            JOptionPane.INFORMATION_MESSAGE);
                    return;
            }

            // Cerrar login
            dispose();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error en la base de datos: " + e.getMessage());
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (SQLException e) {
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

