    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        boolean hayCamposVacios = false;

        if (jTextField1.getText().trim().isEmpty()) {
            hayCamposVacios = true;
        }
        if (jPasswordField1.getPassword().length == 0) {
            hayCamposVacios = true;
        }

        if (hayCamposVacios) {
            JOptionPane.showMessageDialog(null,
                    "Para poder acceder al sistema debe insertar usuario y contraseña.",
                    "Advertencia",
                    JOptionPane.WARNING_MESSAGE);
            if (jTextField1.getText().trim().isEmpty()) {
                jTextField1.requestFocus();
            } else {
                jPasswordField1.requestFocus();
            }
            return;
        }

// Datos ingresados
        String usuarioIngresado = jTextField1.getText().trim();
        String contraseñaIngresada = new String(jPasswordField1.getPassword()).trim();

        Connection conn = null;
        PreparedStatement pst = null;
        ResultSet rs = null;

        try (Connection cn = new conexion().conectar()) {

            // 🔹 Primero verificamos si el usuario existe
            String sqlUsuario = "SELECT Contraseña, Nombre, Modulo, Status, Puesto, Empresa "
                    + "FROM perfilado WHERE Usuario = ?";
            pst = cn.prepareStatement(sqlUsuario);
            pst.setString(1, usuarioIngresado);
            rs = pst.executeQuery();

            if (!rs.next()) {
                // ❌ Usuario no existe
                JOptionPane.showMessageDialog(this,
                        "El usuario no existe.",
                        "Error de autenticación",
                        JOptionPane.ERROR_MESSAGE);
                jTextField1.selectAll();
                jTextField1.requestFocus();
                return;
            }

            // ✅ Usuario encontrado, verificamos contraseña
            String contraseñaReal = rs.getString("Contraseña");
            if (!contraseñaReal.equals(contraseñaIngresada)) {
                // ❌ Contraseña incorrecta
                JOptionPane.showMessageDialog(this,
                        "Contraseña incorrecta.",
                        "Error de autenticación",
                        JOptionPane.ERROR_MESSAGE);
                jPasswordField1.selectAll();
                jPasswordField1.requestFocus();
                return;
            }

            // ✅ Usuario y contraseña correctos
            String nombreEmpleado = rs.getString("Nombre");
            String modulo = rs.getString("Modulo");
            String status = rs.getString("Status");
            String puesto = rs.getString("Puesto");
            String empresaUsuario = rs.getString("Empresa");

            if (!"Esta Disponible".equalsIgnoreCase(status.trim())) {
                JOptionPane.showMessageDialog(this,
                        nombreEmpleado + ", el módulo \"" + modulo + "\" no está disponible.\n"
                        + "Podrá acceder hasta que \"" + modulo + "\" esté disponible.",
                        "Módulo no disponible",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 🔹 Abrir ventana según el módulo
            switch (modulo) {
                case "Alta de Tickets":
                    AltaTickets ventana = new AltaTickets();
                    ventana.setPuesto(puesto);
                    ventana.setVisible(true);
                    break;

                case "Asignacion de Trabajo":
                    if ("Supervisor".equalsIgnoreCase(puesto)) {
                        AsignacionTrabajo ventanaAsignacion = new AsignacionTrabajo();
                        ventanaAsignacion.setPuesto(puesto);
                        ventanaAsignacion.setVisible(true);
                    } else if ("Soporte Tecnico".equalsIgnoreCase(puesto)) {
                        AsignacionTrabajo ventanaAsignacion = new AsignacionTrabajo();
                        ventanaAsignacion.setEmpleadoFiltrado(nombreEmpleado);
                        ventanaAsignacion.setPuesto(puesto);
                        ventanaAsignacion.setVisible(true);
                    }
                    break;

                case "Monitoreo de Tickets":
                    MonitoreoTickets ventanaMonitoreo = new MonitoreoTickets();
                    ventanaMonitoreo.setPuesto(puesto);
                    ventanaMonitoreo.setVisible(true);
                    break;

                case "Gestion de Soluciones":
                    Solucion ventanaSol = new Solucion();
                    ventanaSol.setPuesto(puesto);
                    ventanaSol.setVisible(true);
                    break;

                case "Reporte de Visita":
                    ReporteVisita ventanaRep = new ReporteVisita();
                    ventanaRep.setPuesto(puesto);
                    ventanaRep.setVisible(true);
                    break;

                case "Catalogo-Empleados":
                    Empleados ventanaEmp = new Empleados();
                    ventanaEmp.setPuesto(puesto);
                    ventanaEmp.setVisible(true);
                    break;

                case "Catalogo-Polizas":
                    Polizas ventanaPol = new Polizas();
                    ventanaPol.setPuesto(puesto);
                    ventanaPol.setVisible(true);
                    break;

                case "Perfilado del Sistema":
                    Perfilado perfil = new Perfilado();
                    perfil.setVisible(true);
                    break;

                case "Catalogo-Productos":
                    Productos ventanaProd = new Productos();
                    ventanaProd.setPuesto(puesto);
                    ventanaProd.setVisible(true);
                    break;

                case "Catalogo-Clientes":
                    Clientes ventanaCli = new Clientes();
                    ventanaCli.setPuesto(puesto);
                    ventanaCli.setVisible(true);
                    break;

                case "Monitoreo de Etapas":
                    if ("Supervisor".equalsIgnoreCase(puesto)) {
                        MonitoreoImplementacion ventanaEtapas = new MonitoreoImplementacion();
                        ventanaEtapas.setEmpresaFiltrada(empresaUsuario);
                        ventanaEtapas.setPuesto(puesto);
                        ventanaEtapas.setVisible(true);
                    } else if ("Director".equalsIgnoreCase(puesto)) {
                        MonitoreoImplementacion ventanaEtapas = new MonitoreoImplementacion();
                        ventanaEtapas.setEmpresaFiltrada(empresaUsuario);
                        ventanaEtapas.setPuesto(puesto);
                        ventanaEtapas.setVisible(true);
                    }
                    break;

                case "Reporte de Finanzas":
                    if ("Contador".equalsIgnoreCase(puesto)) {
                        Costos ventanaCostos = new Costos();
                        ventanaCostos.setEmpresaFiltrada(empresaUsuario);
                        ventanaCostos.setPuesto(puesto);
                        ventanaCostos.setVisible(true);
                    } else {
                        Costos ventanaCostos = new Costos();
                        ventanaCostos.setPuesto(puesto);
                        ventanaCostos.setVisible(true);
                    }
                    break;

                case "Catalogo-Gastos":
                    Gastos gastos = new Gastos();
                    gastos.setPuesto(puesto);
                    gastos.setVisible(true);
                    break;

                case "Reporte de Gastos a Detalle":
                    if ("Contador".equalsIgnoreCase(puesto)) {
                        ReporteDetallado reporte = new ReporteDetallado();
                        reporte.setEmpresaFiltrada(empresaUsuario);
                        reporte.setPuesto(puesto);
                        reporte.setVisible(true);
                    } else {
                        ReporteDetallado reporte = new ReporteDetallado();
                        reporte.setPuesto(puesto);
                        reporte.setVisible(true);
                    }
                    break;

                case "Acerca de":
                    AcercaDe acerca = new AcercaDe();
                    acerca.setVisible(true);
                    break;

                case "Menu de Modulos":
                    MenuModulos menu = new MenuModulos();
                    menu.setVisible(true);
                    break;

                case "Menu del Capturista":
                    MenuCapturista menu1 = new MenuCapturista();
                    menu1.setVisible(true);
                    break;

                case "Menu de Soporte Tecnico":
                    MenuSoporte menu2 = new MenuSoporte();
                    menu2.setVisible(true);
                    break;

                case "Menu del Supervisor":
                    MenuSupervisor menu3 = new MenuSupervisor();
                    menu3.setVisible(true);
                    break;

                case "Menu del Contador":
                    MenuContador menu4 = new MenuContador();
                    menu4.setVisible(true);
                    break;

                case "Respaldo de la Base de Datos":
                    RespaldoBD respaldo = new RespaldoBD();
                    respaldo.setVisible(true);
                    break;

                case "Ticketix IA":
                    AgenteIA ia = new AgenteIA();
                    ia.setPuesto(puesto);
                    ia.setVisible(true);
                    break;

                default:
                    JOptionPane.showMessageDialog(this,
                            "El módulo asignado no existe o no está implementado.",
                            "Información",
                            JOptionPane.INFORMATION_MESSAGE);
                    return;
            }

            // Cerrar login
            dispose();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error en la base de datos: " + e.getMessage());
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (SQLException e) {
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

